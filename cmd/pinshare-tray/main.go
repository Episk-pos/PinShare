// openBrowser opens a URL in the default browser
func openBrowser(url string) error {
	var cmd *exec.Cmd

	switch runtime.GOOS {
	case "windows":
		cmd = exec.Command("rundll32", "url.dll,FileProtocolHandler", url)
	case "darwin":
		cmd = exec.Command("open", url)
	default:
		cmd = exec.Command("xdg-open", url)
	}

	return cmd.Start()
}

// showMessage shows a system notification
func showMessage(title, message string) {
	// Log the message
	log.Printf("%s: %s", title, message)

	// Update tooltip temporarily
	systray.SetTooltip(fmt.Sprintf("PinShare - %s", message))
}

// runElevated runs a command with administrator privileges using PowerShell
func runElevated(command string, args ...string) error {
	// Build the argument string
	argStr := ""
	for _, arg := range args {
		argStr += " " + arg
	}

	// Use PowerShell's Start-Process with -Verb RunAs to elevate
	psCmd := fmt.Sprintf("Start-Process -FilePath '%s' -ArgumentList '%s' -Verb RunAs -Wait", command, argStr)

	cmd := exec.Command("powershell", "-Command", psCmd)
	return cmd.Run()
}
