var logFile *os.File

func main() {
	// Ensure we're running on Windows
	if runtime.GOOS != "windows" {
		log.Fatal("This application is only supported on Windows")
	}

	// Set up logging to file since we're a GUI app with no console
	setupLogging()
	defer logFile.Close()

	log.Println("PinShare tray application starting...")

	systray.Run(onReady, onExit)
}

// setupLogging configures logging to a file
func setupLogging() {
	// Try to create log file in ProgramData
	logDir := filepath.Join(os.Getenv("PROGRAMDATA"), "PinShare", "logs")
	if err := os.MkdirAll(logDir, 0755); err != nil {
		// Fall back to temp directory
		logDir = os.TempDir()
	}

	logPath := filepath.Join(logDir, "pinshare-tray.log")
	var err error
	logFile, err = os.OpenFile(logPath, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0644)
	if err != nil {
		// If we can't open log file, log to nowhere
		return
	}

	log.SetOutput(logFile)
	log.SetFlags(log.Ldate | log.Ltime | log.Lshortfile)
}

func onReady() {
	log.Println("onReady called, setting up tray icon...")

	// Set up the tray icon
	iconData, err := loadIcon()
	if err != nil {
		log.Printf("Warning: Failed to load icon.ico: %v, using embedded icon", err)
		iconData = getEmbeddedIcon()
	}

	systray.SetIcon(iconData)
	systray.SetTitle("PinShare")
	systray.SetTooltip("PinShare - Decentralized IPFS Pinning")

	log.Println("Tray icon set, building menu...")

	// Create tray instance
	tray := NewTray()

	// Build menu
	tray.BuildMenu()

	log.Println("Menu built, starting status update loop...")

	// Start status update loop
	go tray.UpdateStatusLoop()

	log.Println("Tray application ready")
}

func onExit() {
	log.Println("PinShare tray application exiting")
}

// loadIcon loads the application icon from file
func loadIcon() ([]byte, error) {
	exePath, err := os.Executable()
	if err != nil {
		return nil, err
	}

	iconPath := filepath.Join(filepath.Dir(exePath), "icon.ico")
	data, err := os.ReadFile(iconPath)
	if err != nil {
		return nil, err
	}

	return data, nil
}

